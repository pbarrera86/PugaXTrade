const {chromium} = require('playwright');
const {execFileSync} = require('node:child_process');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const {expect} = require('playwright/test');
(async()=>{
  const browser=await chromium.launch({headless:true});
  try {
    const page=await browser.newPage();
    const dialogs=[];
    page.on('dialog',async d=>{dialogs.push(d.message());await d.dismiss();});
    await page.goto('http://localhost:3838/');
    await page.getByRole('button',{name:'Iniciar sesión',exact:true}).click();
    await page.getByLabel('Usuario o correo',{exact:true}).fill('ci_browser_fixture');
    await page.getByLabel('Contraseña',{exact:true}).fill('Browser fixture password 2026');
    await Promise.all([page.waitForNavigation(),page.getByRole('button',{name:'Entrar',exact:true}).click()]);
    await page.getByText(/Proceso concluido con éxito\. 500 tickers/).waitFor({timeout:30000});
    const completedMessage=await page.getByText(/Proceso concluido con éxito\. 500 tickers/).textContent();
    const table=page.locator('#main-inst-summary_tbl');
    let ajax=0;
    page.on('request',r=>{if(r.url().includes('/dataobj/')&&!r.url().includes('restore-auth'))ajax++;});
    await table.getByRole('combobox',{name:'Show entries',exact:true}).selectOption('100');
    await table.getByText('Showing 1 to 100 of 500 entries',{exact:true}).waitFor();
    await table.getByRole('link',{name:'Next',exact:true}).or(table.getByRole('button',{name:'Next',exact:true})).click();
    await table.getByText('Showing 101 to 200 of 500 entries',{exact:true}).waitFor();
    await table.getByLabel('Search:',{exact:true}).fill('FIX00042');
    await table.getByText('FIX00042',{exact:true}).waitFor();
    await table.getByRole('cell',{name:'FIX00042',exact:true}).click();
    await expect(page.locator('#main-inst-ticker_detalle')).toHaveValue('FIX00042');
    await expect(page.locator('#main-inst-price_plot .gtitle')).toHaveText('Precio y medias móviles - FIX00042');
    await expect(page.locator('#main-inst-detail_tbl').getByRole('row').filter({hasText:'Precio actual (USD)'})).toContainText('142');
    await page.locator('#main-inst-ticker_detalle').selectOption('FIX00003',{force:true});
    await expect(page.locator('#main-inst-price_plot .gtitle')).toHaveText('Precio y medias móviles - FIX00003');
    await expect(page.locator('#main-inst-detail_tbl').getByRole('row').filter({hasText:'Precio actual (USD)'})).toContainText('103');
    await table.getByLabel('Search:',{exact:true}).fill('');
    await table.getByRole('link',{name:'Next',exact:true}).or(table.getByRole('button',{name:'Next',exact:true})).click();
    await table.getByRole('cell',{name:'FIX00142',exact:true}).click();
    await expect(page.locator('#main-inst-ticker_detalle')).toHaveValue('FIX00142');
    await expect(page.locator('#main-inst-price_plot .gtitle')).toHaveText('Precio y medias móviles - FIX00142');
    assert.equal(ajax,0,'paging and filtering must not require DT Ajax requests');
    await page.getByRole('button',{name:/Exportar Excel$/}).click();
    await page.getByText(/Preparando Excel en segundo plano/).waitFor();
    execFileSync('docker',['exec','--user','shiny','-e','PUGA_TEST_DATABASE=local-disposable','-e','PUGA_PREPARE_FIXTURE_EXPORT=true','-w','/srv/shiny-server/app','puga-ci','Rscript','tests/browser_result_seed.R'],{stdio:'inherit'});
    const [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('link',{name:/Descargar Excel$/}).click()]);
    await download.saveAs('/tmp/puga-browser-export.xlsx');
    assert.equal(await download.failure(),null);
    const bytes=fs.readFileSync('/tmp/puga-browser-export.xlsx');
    assert.equal(bytes.subarray(0,2).toString(),'PK');assert.ok(bytes.length>1000);
    assert.equal(dialogs.length,0,'no DataTables warning may appear');
    await page.reload();
    await page.getByRole('link',{name:/Descargar Excel$/}).waitFor({timeout:30000});
    assert.equal(await page.getByText(/Proceso concluido con éxito\. 500 tickers/).textContent(),completedMessage,'completion duration must stay fixed after export and reload');
    await page.getByLabel('Tickers',{exact:true}).fill('NEW');
    await page.getByRole('button',{name:/Iniciar análisis$/}).click();
    await expect(page.getByRole('button',{name:/Exportar Excel$/})).toBeDisabled();
    await expect(page.getByRole('link',{name:/Descargar Excel$/})).toHaveCount(0);
    await expect(page.locator('#main-inst-summary_tbl .dataTables_wrapper')).toHaveCount(0);
    await expect(page.locator('#main-inst-price_plot .gtitle')).toHaveCount(0);
    console.log('PASS: ticker row/dropdown navigation, paging/filtering, prepared download and replacement clears old outputs');
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
